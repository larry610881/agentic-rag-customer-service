# OpenAI 相容視覺引擎（Gemini 等）額外附加的抑制幻覺指令（Issue #78）。
# Haiku 4.5 曾出現小幻覺；Gemini 版明示「不可補字、看不清楚留空、不得推測數字」。
ANTI_HALLUCINATION_SUFFIX = """

# 抑制幻覺（最高優先級）
- **不可補字**：只輸出圖中真實可見的文字，不得依語意補完字詞或句子。
- **看不清楚留空**：無法辨認的字元或欄位直接留空（或依上方規則填「不詳」），不得猜測。
- **不得推測數字**：價格、日期、百分比、數量必須逐字抄自圖片，不可推算、四捨五入或補零。
"""


def normalize_page_type(raw: str, fallback: str = "catalog") -> str:
    """把 LLM 回的分類文字收斂成合法 page type；解析失敗回 ``fallback``。

    容錯：只取第一個 token、去標點、不分大小寫；也接受 JSON
    ``{"page_type": "..."}``（response_format 路徑）。
    """
    text = (raw or "").strip()
    if not text:
        return fallback
    if text.startswith("{"):
        import json

        try:
            data = json.loads(text)
            candidate = data.get("page_type", "") if isinstance(data, dict) else ""
            if isinstance(candidate, str) and candidate.lower() in _VALID_PAGE_TYPES:
                return candidate.lower()
        except ValueError:
            pass
    token = text.lower().split()[0]
    token = token.strip("\"'`").rstrip(".,:;！。，；").strip()
    return token if token in _VALID_PAGE_TYPES else fallback
